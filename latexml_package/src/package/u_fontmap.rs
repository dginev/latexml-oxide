//! The `U` ("unknown") font encoding: glyphs come from the FAMILY. A raw
//! `\DeclareSymbolFont{AMSa}{U}{msa}{m}{n}` (oz.sty:34, amsfonts users) then
//! decodes through the per-family map `U_msa_fontmap` (`font_decode`; AMSb's `msb` through
//! `U_msb_fontmap`, which amsfonts' `\newsymbol` reaches), which
//! Perl (no `u.fontmap.ltxml`) leaves undecoded. The Euler Roman family `eur` (amsfonts' ueur.fd, eurm/eurb) decodes
//! through the math italic layout, OML, at the 111 slots it shares with cmmi: its TFMs say "TEX MATH ITALIC SUBSET",
//! tftopl gives no slot outside cmmi10's, and rendered they draw cmmi's glyphs upright (program.sty:834-835's
//! `\powersetsymbol` ℘ at "7D, older sn-jnl.cls copies; statex, beilstein.cls, mismath, mathgreeks, sansmath raw);
//! the 17 slots it lacks, 37 and 38 (ϱ and ς, "Euler's missing variants", sansmath.sty:76), 40-47 (harpoons, hooks,
//! triangles), 63 (star), 91-95 (flat, natural, sharp, smile, frown) and 126 (the vector accent), stay undecodable
//! (`U_eur_fontmap`), and are recorded as gaps of the font (`U_eur_fontmap_lacks`): a kernel name declared there —
//! `\star` at "3F, `\vec` at "7E — is U+FFFD with the font's Warning, as pdflatex prints nothing there
//! (OXIDIZED_DESIGN_DIVERGENCES #27). So are msbm's five gaps, "5F and "62-"65 (`U_msb_fontmap_lacks`: amssymb's
//! `AMSa` `\varpropto`, `\Subset`, `\Supset`, `\Cup`, `\Cap` slots, which a name declared in `AMSb` would otherwise
//! decode by name); msam has none. Every family's gaps are generated by tftopl over each size its .fd loads
//! (`U_FONT_GAPS`, tools/perfect_kernel/gen_reference_math_slots.py `--u-font-gaps`); the maps' other empty slots are
//! glyphs with no single character (msbm's negated pairs, msam's `\dabar@`), no gaps.
//! The encoding has no map of its own, bbold loaded or not (its blackboard map is its own family's, `U_blackboard` and
//! `U_bbold`, bbold_sty.rs; OXIDIZED_DESIGN_DIVERGENCES #914): a U symbol font of another family
//! (shuffle.sty, stmaryrd's `stmry`) stays undecoded — U+FFFD, and one Warning per symbol font
//! (OXIDIZED_DESIGN_DIVERGENCES #27) — but for a kernel or AMS name declared at its fontmath.ltx or
//! amssymb slot (sect08.rs `reference_symbol`, OXIDIZED_DESIGN_DIVERGENCES #910) — and the text switch
//! `\fontencoding{U}` falls back to OT1 while `\f@encoding` still names `U` (`\lx@fontencoding`, tex_fonts.rs;
//! OXIDIZED_DESIGN_DIVERGENCES #645). Guards:
//! `perfect_kernel_batch54::declare_math_delimiter_defines_the_symbol`,
//! `perfect_kernel_batch68v::u_symbol_font_without_a_map_stays_undecoded`,
//! `perfect_kernel_batch89c::euler_roman_decodes_as_math_italic`.
//! Witnesses: 2306.04672 (`\shuffle`); 2205.13841, 2212.02709 (program.sty's `U/eur` via sn-jnl.cls copies; neither
//! prints `\powerset`, so no census paper shows the ℘).
use crate::prelude::*;

LoadDefinitions!({
  DeclareFontMap!("U", amsa_fontmap::amsa_table(), "msa");
  DeclareFontMap!("U", amsb_fontmap::amsb_table(), "msb");
  if let Some(oml) = load_font_map("OML") {
    let eur: Rc<[Option<char>]> = oml
      .iter()
      .enumerate()
      .map(|(slot, glyph)| {
        if font_gaps("eur").contains(&slot) {
          None
        } else {
          *glyph
        }
      })
      .collect();
    DeclareFontMap!("U", eur, "eur");
  }
  // The slots each family's fonts lack, as `\DeclareMathSymbol`/`\DeclareMathAccent` read them: a gap of the font
  // (pdflatex: "Missing character"), not a glyph the map has no character for, so no reference name decodes it
  // (sect08.rs `symbol_font_lacks_slot`).
  for (family, gaps) in U_FONT_GAPS {
    let lacks: HashMap<String, String> = gaps
      .iter()
      .map(|slot| (slot.to_string(), String::new()))
      .collect();
    assign_value(&s!("U_{family}_fontmap_lacks"), lacks, Some(Scope::Global));
  }
});

/// The gaps of the mapped `U` family `family` ([`U_FONT_GAPS`]).
fn font_gaps(family: &str) -> &'static [usize] {
  U_FONT_GAPS
    .iter()
    .find(|(name, _)| *name == family)
    .map_or(&[], |(_, gaps)| gaps)
}

